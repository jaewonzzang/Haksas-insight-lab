def canonical(dept: str) -> str:
    """표기를 courses.department 원문으로. 계열/학부 입학 표기는 대학으로.

    대학으로 올린 학생은 학과 코호트에 안 들어간다 — 학과 미선택이라 의도된 동작.
    """
    if dept in FACULTY_COLLEGES:
        return FACULTY_COLLEGES[dept]
    return DEPT_ALIASES.get(dept, dept)


def candidate_departments(student_dept: str) -> list[str]:
    """추천 풀·코호트 대조용 학과 목록. 대학이면 그 대학 + 소속 학과 전체."""
    c = canonical(student_dept)
    if c in DEPT_COLLEGES:
        return [c, *DEPT_COLLEGES[c]]
    return [c]
