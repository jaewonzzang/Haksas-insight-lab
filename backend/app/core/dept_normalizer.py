def canonical(dept: str) -> str:
    """표기 별칭을 courses.department 원문으로. 모르는 이름은 원문 그대로."""
    return DEPT_ALIASES.get(dept, dept)


def candidate_departments(student_dept: str) -> list[str]:
    """합집합 매핑이 있으면 그 목록(복사본), 없으면 정규화한 단일 목록."""
    return list(DEPT_UNIONS.get(student_dept, [canonical(student_dept)]))
