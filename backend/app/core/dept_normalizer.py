# 학사팀 수강내역은 소속을 "X전공"으로, courses.db 는 "X학과"로 적어 코호트 대조가
# 전부 빗나갔다 (14,942명 중 5,036명). 어간 규칙 대신 표로 둔다 — 규칙으로 밀면
# "사회과학부"(계열)가 "사회학과"에 잘못 합쳐진다. 확실한 1:1 만 넣을 것.
# 미해결(A16): 학부/계열 표기(사회과학부·인문학부·영문학부)와 원본 잘림(SCIENCE기반자유전).
